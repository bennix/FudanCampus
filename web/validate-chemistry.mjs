import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const pub=new URL('./public/',import.meta.url);
const manifest=JSON.parse(fs.readFileSync(new URL('campus-manifest.json',pub)));
const a=manifest.buildings.find(a=>a.id==='55');
const data=fs.readFileSync(new URL(a.url,pub));
assert.equal(createHash('sha256').update(data).digest('hex').slice(0,12),a.revision);
assert.equal(data.length,a.bytes);
const g=JSON.parse(data.subarray(20,20+data.readUInt32LE(12)));
const nodes=g.nodes.filter(n=>n.mesh!=null);
assert(nodes.every(n=>n.extras?.building_id==='55'));
const roofs=nodes.filter(n=>n.extras?.component==='portico roof');
assert.deepEqual(roofs.map(n=>n.extras.entrance).sort(),['east','front','rear']);
assert.equal(roofs.find(n=>n.extras.entrance==='east').extras.width,7.2);
assert.equal(new Set(nodes.filter(n=>n.extras?.component==='window glass').map(n=>n.extras.wall_segment)).size,16);
assert(nodes.filter(n=>n.extras?.component==='window glass').every(n=>n.extras.window_width<=2));
assert(g.materials.find(m=>m.name==='Chemistry white roof').pbrMetallicRoughness.baseColorFactor.slice(0,3).every(c=>c>.8));
assert(g.materials.find(m=>m.name==='Chemistry deep red brick').pbrMetallicRoughness.baseColorTexture);
assert(nodes.some(n=>n.name.includes('raised centre')));
console.log('PASS chemistry: 16 windowed facades, 3 tiled porticos, narrow east canopy, white roof, textured deep red brick');
